def test_repeated_errors_are_deduped(home):
    """One bad credential produces the same error all day."""
    entry = _claude_user(
        [{"type": "tool_result", "is_error": True, "content": "401 Unauthorized"}]
    )
    _write_transcript(home, [entry] * 50)
    result = harvest_user(_User(str(home)))

    assert result.errors == ["401 Unauthorized"]


def test_a_successful_tool_result_is_not_an_error(home):
    _write_transcript(
        home,
        [_claude_user([{"type": "tool_result", "content": "ok"}])],
    )
    assert harvest_user(_User(str(home))).errors == []


