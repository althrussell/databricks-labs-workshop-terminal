"""Edge harvest of the session's residue (contract C6, tier 3).

The harvester's value is entirely in what it leaves behind. These tests are
weighted accordingly: the exclusions (file contents, stdout, stack-trace bodies)
get as much attention as the inclusions, because a harvester that quietly starts
shipping tool output turns an opt-in sales feature into a transcript exfiltrator.

The second theme is tolerance. Two agent harnesses write these logs, both change
their envelope between releases, and a parser pinned to one shape fails by
extracting nothing — which is indistinguishable from an attendee who said nothing.
"""

from __future__ import annotations

import json
import os
import subprocess

import pytest

from server import artifacts
from server.artifacts import Artifact, Harvest, harvest_user

from . import synthetic_secrets as fake


class _User:
    """The two attributes the harvester actually reads."""

    def __init__(self, home: str, email: str = "alice@example.com"):
        self.home = home
        self.email = email


@pytest.fixture
def home(tmp_path):
    path = tmp_path / "home"
    (path / ".claude" / "projects" / "p").mkdir(parents=True)
    return path


def _write_transcript(home, entries, name: str = "session.jsonl") -> str:
    path = home / ".claude" / "projects" / "p" / name
    path.write_text("\n".join(json.dumps(e) for e in entries) + "\n")
    return str(path)


def _claude_user(text) -> dict:
    return {"type": "user", "message": {"role": "user", "content": text}}


def _claude_tool(name: str, tool_input: dict) -> dict:
    return {
        "type": "assistant",
        "message": {
            "role": "assistant",
            "content": [{"type": "tool_use", "name": name, "input": tool_input}],
        },
    }


# --- Attendee prompts ---------------------------------------------------------


def test_attendee_prompts_are_captured_verbatim(home):
    _write_transcript(
        home,
        [_claude_user("How do I connect this to our Confluent Kafka cluster?")],
    )
    result = harvest_user(_User(str(home)))

    assert result.prompts == ["How do I connect this to our Confluent Kafka cluster?"]
    assert result.prompt_count == 1


def test_both_string_and_block_content_shapes_are_read(home):
    """Claude sends either, depending on how the turn was composed."""
    _write_transcript(
        home,
        [
            _claude_user("plain string turn"),
            _claude_user([{"type": "text", "text": "block turn"}]),
        ],
    )
    result = harvest_user(_User(str(home)))

    assert result.prompts == ["plain string turn", "block turn"]


def test_a_codex_style_envelope_is_read_too(home):
    """A parser pinned to one harness silently drops the other's whole session."""
    path = home / ".codex" / "sessions" / "2026"
    path.mkdir(parents=True)
    (path / "rollout.jsonl").write_text(
        json.dumps(
            {
                "type": "response_item",
                "payload": {
                    "role": "user",
                    "content": [
                        {"type": "input_text", "text": "migrate our Oracle CDC job"}
                    ],
                },
            }
        )
        + "\n"
    )
    result = harvest_user(_User(str(home)))

    assert result.prompts == ["migrate our Oracle CDC job"]


def test_tool_results_never_become_prompts(home):
    """Tool output arrives on the user role and is the bulk of a transcript."""
    _write_transcript(
        home,
        [
            _claude_user(
                [
                    {
                        "type": "tool_result",
                        "content": "row1,row2,row3\nrow4,row5\n... 40k more rows",
                    }
                ]
            ),
            _claude_user("why is the join so slow?"),
        ],
    )
    result = harvest_user(_User(str(home)))

    assert result.prompts == ["why is the join so slow?"]
    assert not any("row1" in p for p in result.prompts)


def test_harness_injected_pseudo_turns_are_dropped(home):
    """Nobody typed these, and a brief must not quote the harness to a customer."""
    _write_transcript(
        home,
        [
            _claude_user("<command-name>/clear</command-name>"),
            _claude_user("<system-reminder>Your context is running low</system-reminder>"),
            _claude_user("Caveat: The messages below were generated by a hook"),
            _claude_user("[Request interrupted by user]"),
            _claude_user("build me a streaming pipeline"),
        ],
    )
    result = harvest_user(_User(str(home)))

    assert result.prompts == ["build me a streaming pipeline"]
    assert result.prompt_count == 1, "synthetic turns must not inflate engagement"


def test_continuations_are_counted_but_not_summarised(home):
    """"yes" means nothing standalone, but forty of them describe the session.

    Dropping them from the count would understate a highly engaged attendee;
    feeding them to the summariser would spend the context window on noise.
    """
    _write_transcript(
        home,
        [
            _claude_user("build a genie space over our sales data"),
            _claude_user("yes"),
            _claude_user("go ahead"),
            _claude_user("Fix that"),
        ],
    )
    result = harvest_user(_User(str(home)))

    assert result.prompts == ["build a genie space over our sales data"]
    assert result.prompt_count == 4


def test_prompts_are_redacted(home):
    _write_transcript(
        home,
        [_claude_user(f"connect using token {fake.DAPI_TOKEN}")],
    )
    result = harvest_user(_User(str(home)))

