def test_promote_docs_are_described_but_not_shipped(home):
    promote = home / "promote"
    promote.mkdir()
    (promote / "architecture.md").write_text("# Architecture\nKafka to Delta.\n")
    (promote / "jira-stories.md").write_text("# Epic\nBusiness value: fraud losses.\n")
    result = harvest_user(_User(str(home)))

    kinds = {(a.kind, a.title) for a in result.artifacts}
    assert ("promote_doc", "architecture.md") in kinds
    # Named for its content, not its filename markers — a marker list would have
    # dropped exactly the document that states business value.
    assert ("promote_doc", "jira-stories.md") in kinds
    assert all(a.bytes > 0 for a in result.artifacts)
    # Only kind/title/bytes leave the instance.
    assert set(result.artifact_payload()[0]) == {"kind", "title", "bytes"}


