def test_shared_tmp_promote_is_ignored_on_a_shared_instance(tmp_path, monkeypatch):
    """/tmp is shared by uid, so trusting it could brief the wrong company.

    On the supported one-attendee topology it is the promote skill's historical
    output location and must be read; on a shared instance the same directory
    cannot be attributed to anyone.
    """
    shared = tmp_path / "tmp" / "promote"
    shared.mkdir(parents=True)
    (shared / "architecture.md").write_text("# Architecture\n")
    monkeypatch.setattr(
        artifacts, "_document_roots",
        lambda home, *, include_shared_tmp: (
            [str(shared)] if include_shared_tmp else []
        ),
    )
    home = tmp_path / "home"
    home.mkdir()

    alone = harvest_user(_User(str(home)), single_attendee=True)
    shared_instance = harvest_user(_User(str(home)), single_attendee=False)

    assert [a.title for a in alone.artifacts] == ["architecture.md"]
    assert shared_instance.artifacts == []


def test_the_real_root_list_includes_tmp_promote_only_when_alone(tmp_path):
    alone = artifacts._document_roots("/h", include_shared_tmp=True)
    shared = artifacts._document_roots("/h", include_shared_tmp=False)

    assert "/tmp/promote" in alone
    assert "/tmp/promote" not in shared
    assert "/h/promote" in shared


# --- Commit subjects ----------------------------------------------------------


def _git_repo(path, subjects):
    """A throwaway repo, isolated from the developer's global git config.

    Without the config isolation a machine with commit signing enabled blocks on
    a passphrase prompt and the suite hangs rather than fails.
    """
    path.mkdir(parents=True, exist_ok=True)
    env = {
        **os.environ,
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_CONFIG_SYSTEM": os.devnull,
        "GIT_AUTHOR_NAME": "A", "GIT_AUTHOR_EMAIL": "a@x.com",
        "GIT_COMMITTER_NAME": "A", "GIT_COMMITTER_EMAIL": "a@x.com",
    }
    run = lambda *args: subprocess.run(  # noqa: E731
        ["git", "-c", "commit.gpgsign=false", *args],
        cwd=path, check=True, env=env, capture_output=True, timeout=30,
    )
    run("init", "-q")
    for i, subject in enumerate(subjects):
        (path / f"f{i}.txt").write_text(subject)
        run("add", "-A")
        run("commit", "-q", "-m", subject)


def test_commit_subjects_are_captured(home):
    _git_repo(
        home / "projects" / "fraud",
        ["Add Kafka bronze ingest", "Score transactions with the served model"],
    )
    result = harvest_user(_User(str(home)))

    titles = {a.title for a in result.artifacts if a.kind == "commit"}
    assert "Add Kafka bronze ingest" in titles
    assert "Score transactions with the served model" in titles


def test_a_directory_without_git_is_skipped(home):
    plain = home / "projects" / "scratch"
    plain.mkdir(parents=True)
    (plain / "notes.txt").write_text("x")
    assert harvest_user(_User(str(home))).artifacts == []


def test_commits_cannot_crowd_out_documents(home):
    """The architecture doc is worth more than the fiftieth commit subject."""
    promote = home / "promote"
    promote.mkdir()
    (promote / "architecture.md").write_text("# Architecture\n")
    _git_repo(home / "projects" / "app", [f"commit {i}" for i in range(60)])
    result = harvest_user(_User(str(home)))

    commits = [a for a in result.artifacts if a.kind == "commit"]
    assert len(commits) == artifacts.MAX_COMMITS
    assert any(a.kind == "promote_doc" for a in result.artifacts)


# --- Failure behaviour --------------------------------------------------------


def test_an_empty_home_yields_an_empty_harvest(tmp_path):
    result = harvest_user(_User(str(tmp_path / "nonexistent")))

    assert result.is_empty()
    assert result.prompt_count == 0


def test_emptiness_is_reported_rather_than_invented(home):
    """A summary over nothing would be fabrication, so callers must be able to tell."""
    assert harvest_user(_User(str(home))).is_empty() is True
    _write_transcript(home, [_claude_user("what is unity catalog?")])
    assert harvest_user(_User(str(home))).is_empty() is False


def test_a_corrupt_transcript_line_does_not_lose_the_file(home):
    path = home / ".claude" / "projects" / "p" / "session.jsonl"
    path.write_text(
        "{not json\n"
        + json.dumps(_claude_user("real question about lakeflow"))
        + "\n"
        + "\x00\x01\n"
    )
    result = harvest_user(_User(str(home)))

    assert result.prompts == ["real question about lakeflow"]


def test_an_enormous_single_line_is_skipped_as_a_tool_dump(home):
    _write_transcript(
        home,
        [
            _claude_user("a" * (artifacts.MAX_LINE_BYTES + 10)),
            _claude_user("small real question"),
        ],
    )
    result = harvest_user(_User(str(home)))

    assert result.prompts == ["small real question"]


def test_a_harvest_never_raises(home, monkeypatch):
    """Both callers are best-effort paths where an exception costs something real."""
    monkeypatch.setattr(
        artifacts, "_scan_transcripts",
        lambda *a, **k: (_ for _ in ()).throw(RuntimeError("disk gone")),
    )
    assert isinstance(harvest_user(_User(str(home))), Harvest)


def test_artifact_payload_is_metadata_only():
    payload = Artifact(kind="promote_doc", title="architecture.md", bytes=4096).payload()
    assert payload == {"kind": "promote_doc", "title": "architecture.md", "bytes": 4096}
