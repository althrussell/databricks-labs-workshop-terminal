def test_prompt_capture_is_bounded(home):
    _write_transcript(
        home,
        [_claude_user(f"question number {i} about lakebase") for i in range(400)],
    )
    result = harvest_user(_User(str(home)))

    assert len(result.prompts) == artifacts.MAX_PROMPTS
    # The count is not capped: it is the cheap engagement signal.
    assert result.prompt_count == 400


def test_an_oversized_prompt_is_truncated(home):
    _write_transcript(home, [_claude_user("x" * 5000)])
    result = harvest_user(_User(str(home)))

    assert len(result.prompts[0]) == artifacts.MAX_PROMPT_CHARS


